function txt = server_readme_text(nDep, nRec, catVersion, gitHash)
% SERVER_README_TEXT  Text of README.md at the root of the published catalog.
%
%   txt = server_readme_text(nDep, nRec, catVersion, gitHash)
%
% nDep, nRec   deployments and instrument-records in the manifest
% catVersion   catalog version the README describes, e.g. '2026-10-16.1'
% gitHash      pipeline commit that catalog version was pushed from
%
% Called by scripts/copy_to_server.m on every push, and by
% scripts/write_server_readme.m to rewrite the README alone without making a
% new catalog version. Readers of the server copy may never open the
% repository, so the known limitations are stated here as well as in the
% repository README; keep the two in step.
% Author: Holden Leslie-Bole, 2026

L = {
'# PUV Vector Processed Data (Holden Leslie-Bole)'
''
sprintf(['Processed Nortek Vector PUV data: %d instrument-records from %d deployments ' ...
         'on the San Diego County coast and Santa Catalina Island.'], nRec, nDep)
sprintf('Generated: %s.', char(datetime('today', 'Format', 'yyyy-MM-dd')))
''
'## Source'
''
'Pipeline: https://github.com/holdenlesliebole/Nortek_Vector_PUV_Pipeline'
sprintf('Catalog version %s, pushed from pipeline commit %s. CHANGELOG.md says what', catVersion, gitHash)
'changed in each version.'
''
'## Levels'
''
'- **Level1_QC**: QC''d 2 Hz timeseries: PUV struct with `time` (UTC),'
'  `P` (pressure, dBar), `BuoyCoord.{U,V,W}` (buoy frame, +x WEST, +y NORTH),'
'  `InstrCoord` (instrument frame), `T` (temperature), `doffp`, `LATLON`.'
'  Burst-merged, clock-drift-corrected, with battery cutoff truncation.'
'  Top-of-hour alignment is applied at L2, not here; L1 covers the full'
'  sample range.'
'- **Level2_QC**: Spectral analysis on 1-hour segments (7200 samples @ 2 Hz):'
'  multi-taper PSD (DPSS, NW = 4, K = 6 tapers with eigenvalue > 0.99),'
'  surface elevation spectrum S_eta(f), bulk wave parameters (Hs, Tp, mean'
'  direction, spread), directional Fourier coefficients (a1, b1, a2, b2),'
'  Z-test, radiation stress, segment-mean cross-shore and alongshore velocity'
'  (uMean, vMean). Velocities are rotated to shore-normal (+x onshore, +y'
'  alongshore north).'
'  (Switched from 17-min to 1-hour segments in May 2026. The legacy 17-min L2'
'  archive was deleted 2026-07-28; its manifest is in the repository under'
'  docs/.)'
'- **Level3_QC**: Forcing-derived quantities: energy partitioning by frequency'
'  band, bed velocity / stress, Shields parameter, Rouse number, MOP shoaled'
'  reference, tidal and subtidal currents, NOAA tidal depth.'
'- **Level4_QC**: IG / bound-wave dynamics: surface elevation timeseries by'
'  band (eta_total, eta_swell, eta_ig), Sheremet incident/reflected IG split'
'  with R^2(f) and IG flux, bispectrum / bicoherence with skewness and asymmetry,'
'  swell self-coupling and swell-IG difference-coupling metrics.'
'- **Level4_xspec**: Pairwise IG cross-spectra across co-deployed instruments:'
'  Welch cross-spectrum S_ij(f), coherence^2(f), and cross-phase phi(f) per'
'  segment, with pair geometry (alongshore/cross-shore separation in the pair''s'
'  mean shore-normal frame) and aggregated band statistics. One xspec.mat per'
'  deployment with more than one instrument.'
''
'L1 is included so the catalog can be rebuilt from this archive alone.'
''
'## Known limitations'
''
'Read these before using the data. The repository README ("Known limitations")'
'has the detail.'
''
'- **Two records do not measure the ocean.** RUBY22/MOP582_30m has a dead'
'  pressure transducer (Hs < 0.06 m on 2,668 "valid" segments; deployed below'
'  its rated depth). RUBY22/MOP579_6m reads 44% high against the MOP reference'
'  with R^2 = 0.22. Both are in the catalog and both are excluded from reported'
'  statistics (`shared/excluded_records.m` in the repository).'
'- **Disputed headings.** 12 records keep a compass heading that differs from'
'  the logged mount heading by more than 10 deg: TOR14B, TOR14C, TOR15A,'
'  TOR15D, TOR17B and TOR17D (MOP591_9m), COR17D/MOP158_9m, CDF15A and CDF15C'
'  (MOP677_9m), TOR24W/MOP586_10m, TOR25S/MOP586_15m and SIO25E/SIO_6m. Mean'
'  direction, Sxy and current direction on these are uncertain by at least'
'  that much (`shared/heading_disputed_records.m`).'
'- **Grain size.** 42 of 65 L3 records use a 250 um placeholder D50. Bed'
'  stress, Shields, mobilization, settling velocity and Rouse on those records'
'  will change when measured values arrive. L4 does not use D50.'
'- **`doffp` is fixed per deployment.** The bed moved up to 23 cm in the'
'  logged deployments; that moves depth, Hs/h and Ursell by about 3% and bed'
'  stress by under 0.3%. TOR15B''s pressure port was within 4 cm of burial at a'
'  mid-deployment inspection (`doffp` fell about 55 cm from the 0.59 m applied):'
'  treat its depth, Hs/h and nonlinearity metrics as unreliable.'
'  IB18W and IB19S carry `doffp` values whose source is unknown.'
'- **TOR14A clock.** Its +7 h clock offset is taken from the other 2014-15'
'  records; with 45 valid segments it could not be checked against the tide.'
'- **Unsourced geometry.** 69 `doffp` / `latlon` / `shorenormal` values had no'
'  recorded source at the last audit (2026-07-28). Treat them as unverified.'
''
'## Layout'
''
'```'
'Processed_HLB/'
'  README.md'
'  manifest.csv      : per-file index (deployment, instrument, depth, time range, sizes,'
'                      sha256, build_id, git_hash, backfilled, catalog_version_first)'
'  CHANGELOG.md      : what changed in each catalog version, and how to tell old from new'
'  manifests/        : every previous manifest.csv'
'  <file>.prov.json  : beside every .mat: how it was built (code, applied choices, parents)'
'  <deployment>/'
'    Level1_QC/      : *_processed.mat (QC''d 2 Hz timeseries)'
'    Level2_QC/      : *_L2.mat'
'    Level3_QC/      : *_L3.mat'
'    Level4_QC/      : *_L4.mat'
'    Level4_xspec/   : xspec.mat'
'```'
''
'## Conventions'
''
'- Coordinate system: x cross-shore (positive onshore), y alongshore (positive north)'
'- Vertical: NAVD88 (MSL = 0.774 m, MHW = 1.344 m)'
'- Times: UTC, datetime'
'- File naming: `<label>_L<N>.mat` (L1: `<label>_processed.mat`), where the label is'
'  usually `<MOP or site>_<depth>m` (e.g. MOP580_7m_L2.mat); Catalina is `CAT_isl`.'
''
'## RUBY22 vs Ruby2D'
''
'- **RUBY22/** is the full processed Ruby2D 2021-2022 cross-shore array at'
'  Torrey Pines, ingested via the same pipeline as the rest of the catalog'
'  (3 instruments at MOP578 10m, MOP579 6m, MOP582 30m).'
'- **Ruby2D/**, if present, contains a single-instrument Level2 reprocess of'
'  the legacy archived L1 file, used for the head-to-head validation against'
'  the legacy pipeline (`docs/pipeline_comparison_legacy.md` in the source'
'  repo). It is not a new deployment.'
''
'## CAT21A / CAT21B'
''
'Two Catalina Island deployments at Pebbly Beach, outside CDIP MOP coverage.'
'CAT21A runs 19 Feb - 17 Jun 2021 (CATISL03, 2,812 hourly segments, 1,861'
'valid). CAT21B runs 17-25 Aug 2021 (CATISL02, 196 segments, only 5 valid).'
'With no MOP station, L2 rotates to a manual shore-normal of 63 deg (offshore'
'bearing, +-8 deg), set from the mean-current axis, a GPS survey during the'
'deployment and imagery. The tidal depth in L3 is NOAA 9410079 (Avalon,'
'1.9 km away) since catalog 2026-10-16.1; earlier versions used 9410230'
'(La Jolla).'
''
'## Contact'
''
'Holden Leslie-Bole <hlesliebole@ucsd.edu>, Scripps Institution of Oceanography.'
};
txt = sprintf('%s\n', L{:});
end
