function gs = site_grain_size(site)
% SITE_GRAIN_SIZE  Per-site grain-size statistics for inner-shelf instrument sites.
%
%   gs = site_grain_size('MOP586_5m')
%
%   Returns struct with fields (all sizes in METERS):
%     D16, D50, D84, D90   - percentile grain diameters
%     sorting              - geometric sorting sigma = sqrt(D84/D16)
%     source               - measurement origin / file
%     date                 - sampling date (YYYY-MM or '')
%     status               - 'measured' | 'extrapolated' | 'assumed_default'
%     notes                - caveat / context
%
% MEASURED entries are from a **BetterSizer S3 Plus** LPA, which reports
% D3-D97 natively (no interpolation). Optical model `silica0.1` (refractive
% index 1.544, absorption 0.1) -- the only model run at all three TBR23 sites.
% Model sensitivity is small: at MOP580 5m, where all four models were run,
% D50 spans 2.6% and D84 spans 0.8%.
%
% SUPERSEDED 2026-07-31: these values previously came from a Fritsch
% Analysette 22 NanoTec (TBR23 grab samples, May/Jun 2023, analyzed 28 June
% 2023), where only D50 was the instrument's internal median and D16/D84/D90
% were log-linear interpolations on a coarse 10-bin Q3 CDF rescaled by
% (PDF_D50 / interp_D50). The same physical TBR23 sand was re-run on the
% S3 Plus (28 Oct 2024) to standardize it against the rest of the sampling
% campaign; the S3 Plus percentiles are adopted because they are both the
% standardized and the more directly measured values. The tail percentiles
% moved most (D84 -4 to -20%), consistent with the Fritsch D84 having been a
% coarse-bin interpolation artifact. Fritsch values are preserved in
% `Research/sediment_grain_size/fritsch_analysette/` for reference.
%
% Raw exports + provenance + the propagation study:
% `Research/sediment_grain_size/` (README.md).
%
% EXTRAPOLATED entries follow the MOP586 cross-shore D50 fining trend
% (5m -> 7m: 268 -> 228 um, ~17% finer per 2m depth; log-linear extrapolation)
% with sorting fixed at the 7m value. Update with measured values when LPA
% samples become available.
%
% ASSUMED_DEFAULT entries (Solana, SIO) are placeholder regional values from
% MOP586 7m until site-specific LPA is collected.
%
% USAGE
%   gs = site_grain_size('MOP586_5m');
%   ks = 2.5 * gs.D84;                  % Wiberg-Smith roughness
%   [tau_b, fw, Aw] = bed_stress_ks(Ub, Tp, ks, rho);
%
% TO ADD A NEW SAMPLE: append an entry to T below (status='measured'),
% replacing or augmenting the matching extrapolation.
%
% Author: Holden Leslie-Bole, 2026-05-23 (Paper 2 audit of bed-stress methods)

% --- MEASURED: TBR23 subaqueous grabs, 18 May 2023; run on the S3 Plus 28 Oct 2024 ---
T = struct('site',{},'D16',{},'D50',{},'D84',{},'D90',{},'sorting',{}, ...
           'source',{},'date',{},'status',{},'notes',{});

T(end+1) = struct( ...
    'site','MOP580_5m', ...
    'D16', 196.5e-6, 'D50', 361.9e-6, 'D84', 699.5e-6, 'D90', 845.3e-6, 'sorting', 1.89, ...
    'source','BetterSizer S3 Plus, "20230518_00580_00586_Torrey_Dive.xls" (silica0.1)', ...
    'date','2023-05', 'status','measured', ...
    'notes','Coarsest + most poorly sorted of the three. Coarse tail: D90=845, D95=1071um, so ~6% coarser than 1mm (Fritsch had put this at ~9%). Fritsch gave D50=320, D84=730, sorting 2.18.');

T(end+1) = struct( ...
    'site','MOP586_5m', ...
    'D16', 157.6e-6, 'D50', 246.4e-6, 'D84', 361.5e-6, 'D90', 399.8e-6, 'sorting', 1.51, ...
    'source','BetterSizer S3 Plus, "20230518_00580_00586_Torrey_Dive.xls" (silica0.1)', ...
    'date','2023-05', 'status','measured', ...
    'notes','Moderately sorted. Fritsch gave D50=268, D84=428, sorting 1.71. NB D84 is the most optical-model-sensitive value in the set (344.5-398.8um across models).');

T(end+1) = struct( ...
    'site','MOP586_7m', ...
    'D16', 136.8e-6, 'D50', 217.4e-6, 'D84', 327.5e-6, 'D90', 362.9e-6, 'sorting', 1.55, ...
    'source','BetterSizer S3 Plus, "20230518_00580_00586_Torrey_Dive.xls" (silica0.1)', ...
    'date','2023-05', 'status','measured', ...
    'notes','Finest of the three, consistent with cross-shore fining. Fritsch gave D50=228, D84=412, sorting 1.70.');

% --- EXTRAPOLATED: MOP586 cross-shore fining trend, no measurement yet ---

T(end+1) = struct( ...
    'site','MOP586_10m', ...
    'D16', 110e-6, 'D50', 179e-6, 'D84', 311e-6, 'D90', 348e-6, 'sorting', 1.68, ...
    'source','log-linear extrapolation of MOP586 5m/7m D50 trend', ...
    'date','', 'status','extrapolated', ...
    'notes',['STALE EXTRAPOLATION -- basis changed 2026-07-31. Assumed D50 from a ' ...
             'log-linear fit to the OLD Fritsch 5m=268/7m=228 pair -> 10m=179um. ' ...
             'MEASURED S3 Plus values now exist from the 14-Nov-2023 dive: ' ...
             'D16=107.7 D50=169.4 D84=252.5 D90=278.9um ' ...
             '("20231114_00580_00586_Torrey_Dive.xls", Sand1.6). NOT yet adopted ' ...
             '(no Paper-1 dependency; would affect Paper 2). REPLACE WITH MEASURED.']);

T(end+1) = struct( ...
    'site','MOP586_15m', ...
    'D16', 75e-6, 'D50', 120e-6, 'D84', 208e-6, 'D90', 233e-6, 'sorting', 1.68, ...
    'source','log-linear extrapolation of MOP586 5m/7m D50 trend', ...
    'date','', 'status','extrapolated', ...
    'notes',['STALE EXTRAPOLATION -- basis changed 2026-07-31. Assumed D50 from a ' ...
             'log-linear fit to the OLD Fritsch pair -> 15m=120um. MEASURED S3 Plus ' ...
             'values now exist from the 14-Nov-2023 dive: D16=94.86 D50=144.1 ' ...
             'D84=214.4 D90=239.8um ("20231114_00580_00586_Torrey_Dive.xls", Sand1.6) ' ...
             '-- 20% coarser than the extrapolation. NOT yet adopted (no Paper-1 ' ...
             'dependency; would affect Paper 2). REPLACE WITH MEASURED.']);

T(end+1) = struct( ...
    'site','MOP580_7m', ...
    'D16', 144.6e-6, 'D50', 226.8e-6, 'D84', 340.4e-6, 'D90', 377.6e-6, 'sorting', 1.53, ...
    'source','BetterSizer S3 Plus, "20231114_00564_00586_Torrey_Dive.xls" (silica0.1)', ...
    'date','2023-11', 'status','measured', ...
    'notes',['MEASURED 2026-07-31, replacing the previous inherit-from-MOP586_7m ' ...
             'extrapolation. NB the grab is from the 18-Nov-2023 dive, 6 months AFTER ' ...
             'the May-Jul 2023 TBR23 deployment -- the only sample ever taken at ' ...
             '"7 south". It sits within 4% of the value it replaces (D50 226.8 vs ' ...
             '217.4 um), so adopting it changes little but removes the extrapolation.']);

% --- ASSUMED_DEFAULT: other altimeter sites, no LPA ---

T(end+1) = struct( ...
    'site','MOP654_7m', ...           % Solana Beach
    'D16', 136.8e-6, 'D50', 217.4e-6, 'D84', 327.5e-6, 'D90', 362.9e-6, 'sorting', 1.55, ...
    'source','assumed_default = MOP586_7m (no Solana LPA)', ...
    'date','', 'status','assumed_default', ...
    'notes','SOLANA: no LPA. Used Torrey 7m as regional default. Different site morphology (Cardiff cell, more shell hash near Tabletops headland) may give meaningfully different grain size. PRIORITY for new sampling.');

T(end+1) = struct( ...
    'site','MOP511_6m', ...           % SIO Pier
    'D16', 157.6e-6, 'D50', 246.4e-6, 'D84', 361.5e-6, 'D90', 399.8e-6, 'sorting', 1.51, ...
    'source','assumed_default = MOP586_5m (no SIO LPA)', ...
    'date','', 'status','assumed_default', ...
    'notes','SIO Pier: no LPA. Used Torrey 5m. SIO bed is canyon-influenced; may have finer/coarser tail. PRIORITY for new sampling.');

% --- Look up ---
found = strcmp({T.site}, site);
if ~any(found)
    valid = strjoin({T.site}, ', ');
    error('site_grain_size:unknown', ...
        'No grain-size entry for site "%s". Available: %s. Add a new entry to site_grain_size.m.', ...
        site, valid);
end
gs = T(find(found, 1));
end
